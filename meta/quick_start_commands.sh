# =============================================================================
# СОЗДАНИЕ НОВОГО КУРСА
# =============================================================================

# 1. Замените 'NewCourse' на название вашего курса
COURSE_NAME="NewCourse"

# 2. Создайте папку курса
mkdir -p "Courses/$COURSE_NAME"

# 3. Создайте description.md (отредактируйте содержимое)
cat > "Courses/$COURSE_NAME/description.md" << 'EOF'
# Курс: Название курса

## Описание курса
Краткое описание курса, его применимость и важность.

## Цели курса
После прохождения курса слушатель:
- понимает основные концепции
- умеет применять знания на практике
- ориентируется в терминологии

## Целевая аудитория
- Разработчики начального уровня
- Студенты технических специальностей

## Предварительные требования
- Базовое понимание программирования
- Знакомство с терминалом

## План курса
1. Введение и основы
2. Практические примеры
3. Продвинутые темы
4. Заключение

Примерная длительность: 8-12 часов
EOF

# 4. Создайте структуру модулей (настройте под ваш курс)
mkdir -p "Courses/$COURSE_NAME/01_Introduction"
mkdir -p "Courses/$COURSE_NAME/02_Basics"
mkdir -p "Courses/$COURSE_NAME/03_Advanced"
mkdir -p "Courses/$COURSE_NAME/04_Conclusion"

# 5. Создайте README курса
cat > "Courses/$COURSE_NAME/README.md" << 'EOF'
# Название курса

Краткое описание курса.

## Структура курса

1. [Введение](01_Introduction/)
2. [Основы](02_Basics/)
3. [Продвинутые темы](03_Advanced/)
4. [Заключение](04_Conclusion/)

## Как изучать

1. Читайте лекции последовательно
2. Выполняйте практические задания
3. Проходите квизы для закрепления
4. Используйте дополнительные материалы

## Ресурсы

- [Документация](https://example.com)
- [Практические примеры](https://github.com/example)
EOF

# 6. Создайте файлы для каждого модуля
for module in "Courses/$COURSE_NAME"/*/; do
    if [ -d "$module" ]; then
        touch "$module/lecture.md"
        touch "$module/quiz.md"
        echo "Создан модуль: $module"
    fi
done

echo "Курс $COURSE_NAME создан! Теперь заполните содержимое модулей."
echo "Используйте шаблоны из meta/LECTURE_TEMPLATE.md и meta/QUIZ_TEMPLATE.md"

